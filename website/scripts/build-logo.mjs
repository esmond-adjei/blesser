/**
 * Turn the app's React logo component into an inline Astro component.
 *
 * The mark is a single path that fills the whole tile, so inlining it costs
 * nothing at request time and lets the ink follow the theme. SVGO trims the
 * path precision first: the same artwork, about a third of the bytes.
 *
 *   node website/scripts/build-logo.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { optimize } from "svgo"

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, "../..")
const source = resolve(repo, "webapp/src/components/layout/AppLogo.tsx")
const target = resolve(repo, "website/src/components/Logo.astro")
const tmp = resolve(tmpdir(), "graduator-logo-build")

mkdirSync(tmp, { recursive: true })

const component = readFileSync(source, "utf8")
const start = component.indexOf("<svg")
const end = component.lastIndexOf("</svg>") + "</svg>".length
if (start < 0 || end < 0) throw new Error("no <svg> found in AppLogo.tsx")

let svg = component.slice(start, end)
svg = svg.replace(/className=\{cn\("[^"]*", className\)\}/, 'class="__CLASS__"')
svg = svg.replace(/id=\{clipId\}/g, 'id="graduator-mark"')
svg = svg.replace(/clipPath=\{`url\(#\$\{clipId\}\)`\}/g, 'clip-path="url(#graduator-mark)"')
svg = svg.replace(/fillRule=/g, "fill-rule=")

const { data: optimized } = optimize(svg, {
  multipass: true,
  plugins: [
    { name: "removeViewBox", active: false },
    // The mark is drawn at 736px wide; a tenth of a unit is invisible at
    // any size we use it, and it takes the path from 43 KB to 11 KB.
    { name: "convertPathData", params: { floatPrecision: 1 } },
    { name: "cleanupNumericValues", params: { floatPrecision: 1 } },
  ],
})
writeFileSync(resolve(tmp, "logo.min.svg"), optimized)

const viewBox = optimized.match(/viewBox="[^"]+"/)?.[0] ?? 'viewBox="90 109 736 701"'
const inner = optimized.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").trim()

const astro = `---
interface Props {
  class?: string
}

const { class: className = "size-8" } = Astro.props
---

<!-- Generated by website/scripts/build-logo.mjs from the app's AppLogo. -->
<svg
  ${viewBox}
  role="img"
  aria-label="Graduator logo"
  class={\`size-9 shrink-0 object-contain text-navy-900 dark:text-navy-50 \${className ?? ""}\`}
>
${inner}
</svg>
`

writeFileSync(target, astro)
console.log(
  `logo: ${(svg.length / 1024).toFixed(1)} KB raw -> ${(optimized.length / 1024).toFixed(1)} KB optimized`,
)
