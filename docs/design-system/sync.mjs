#!/usr/bin/env node
// Copies the design system into the apps that use it: the web app and the
// marketing site. Each builds on its own (the web app's Docker context is
// webapp/), so each carries its own copy rather than reaching up into docs/.
//
//   node docs/design-system/sync.mjs          write the copies
//   node docs/design-system/sync.mjs --check  exit 1 when a copy is stale (CI)
//
// Edit the sources here, never the copies.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "../..")
const check = process.argv.includes("--check")

const HEADER = "/* Generated by docs/design-system/sync.mjs from docs/design-system. Edit the source, then run make design-system. */\n"

const FACES = {
  sans: [
    ["Instrument Sans", "InstrumentSans.woff2", "normal", "400 700"],
    ["Instrument Sans", "InstrumentSans-Italic.woff2", "italic", "400 700"],
  ],
  serif: [
    ["Newsreader", "Newsreader.woff2", "normal", "200 800"],
    ["Newsreader", "Newsreader-Italic.woff2", "italic", "200 800"],
  ],
}

// The app never sets the serif (brand book, Typography), so it ships the sans only.
const TARGETS = [
  { dest: "webapp/src/styles/design-system", faces: ["sans"] },
  { dest: "website/src/styles/design-system", faces: ["sans", "serif"] },
]

function fontsCss(faces) {
  const rules = faces.flatMap((f) => FACES[f]).map(
    ([family, file, style, weight]) =>
      `@font-face {\n  font-family: "${family}";\n  src: url("./fonts/${file}") format("woff2");\n  font-weight: ${weight};\n  font-style: ${style};\n  font-display: swap;\n}\n`,
  )
  return HEADER + rules.join("\n")
}

function outputs({ faces }) {
  const read = (p) => fs.readFileSync(path.join(here, p))
  // The bundle loads Google Fonts for standalone use; the apps self-host.
  const bundle = read("components/bundle.css")
    .toString()
    .replace(/^@import url\("https:\/\/fonts\.googleapis\.com[^\n]*\n/m, "")
  const files = {
    "tokens.css": HEADER + read("tokens/tokens.css").toString(),
    "components.css": HEADER + bundle,
    "fonts.css": fontsCss(faces),
  }
  for (const f of faces)
    for (const [, file] of FACES[f]) files[`fonts/${file}`] = read(`fonts/web/${file}`)
  return files
}

let stale = 0
for (const target of TARGETS) {
  const dir = path.join(root, target.dest)
  const want = outputs(target)
  for (const [name, content] of Object.entries(want)) {
    const file = path.join(dir, name)
    const have = fs.existsSync(file) ? fs.readFileSync(file) : null
    if (have && Buffer.compare(have, Buffer.from(content)) === 0) continue
    if (check) {
      console.error(`stale: ${path.relative(root, file)}`)
      stale++
      continue
    }
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, content)
    console.log(`wrote ${path.relative(root, file)}`)
  }
}
if (stale) {
  console.error(`${stale} design-system file(s) out of date: run make design-system`)
  process.exit(1)
}
